val LocalCadenceColors = staticCompositionLocalOf { LightCadenceColors }

object CadenceThemeTokens {
  val colors: CadenceSemanticColors
    @Composable @ReadOnlyComposable get() = LocalCadenceColors.current
}

@Composable
fun CadenceTheme(
  themeMode: ThemeMode = ThemeMode.SYSTEM,
  dynamicColor: Boolean = false,
  content: @Composable () -> Unit,
) {
  val isDark =
    when (themeMode) {
      ThemeMode.SYSTEM -> isSystemInDarkTheme()
      ThemeMode.LIGHT -> false
      ThemeMode.DARK -> true
    }

  val colorScheme =
    when {
      dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
        val context = LocalContext.current
        if (isDark) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
      }
      isDark -> DarkColorScheme
      else -> LightColorScheme
    }

  val semanticColors = if (isDark) DarkCadenceColors else LightCadenceColors

  CompositionLocalProvider(LocalCadenceColors provides semanticColors) {
    MaterialTheme(
      colorScheme = colorScheme,
      typography = CadenceTypography,
      shapes = CadenceShapes,
      content = content,
    )
  }
}
